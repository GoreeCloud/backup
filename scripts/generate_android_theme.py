#!/usr/bin/env python3
"""Generate native Compose Material3 light/dark colors from the tracked GC UI CSS.

The tracked stylesheet is a sourced, attributed snapshot from GoreeCloud/gc-ui.
Do not hand-edit generated Kotlin values or invent product-specific brand colors.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "web/src/gc-tokens.css"
DESTINATION = ROOT / "android/app/src/main/java/com/goreecloud/backup/GoreeCloudUiTheme.kt"

LIGHT_START = ':root, .gc-app[data-gc-theme] {'
DARK_START = ':root[data-gc-theme="dark"], .gc-app[data-gc-theme="dark"] {'

ROLES = (
    ("primary", "brand"),
    ("onPrimary", "on-brand"),
    ("primaryContainer", "brand-container"),
    ("onPrimaryContainer", "on-brand-container"),
    ("secondary", "text-soft"),
    ("onSecondary", "surface"),
    ("background", "canvas"),
    ("onBackground", "text"),
    ("surface", "surface"),
    ("onSurface", "text"),
    ("surfaceVariant", "surface-tonal"),
    ("onSurfaceVariant", "text-soft"),
    ("outline", "outline"),
    ("outlineVariant", "outline-soft"),
    ("error", "negative"),
    ("onError", "on-negative"),
)


def parse_colors(text: str, marker: str) -> dict[str, str]:
    positions = list(re.finditer(r"^" + re.escape(marker) + r"$", text, re.MULTILINE))
    if len(positions) != 1:
        raise ValueError("Expected exactly one top-level GC UI token scope")
    scope = text[positions[0].end():].split("}", 1)[0]
    values = {
        name: hexvalue.upper()
        for name, hexvalue in re.findall(
            r"--gc-([a-z0-9-]+):\s*(#[0-9a-fA-F]{6});", scope
        )
    }
    missing = [token for _, token in ROLES if token not in values]
    if missing:
        raise ValueError("Missing canonical GC UI color tokens")
    return values


def generate(text: str) -> str:
    light = parse_colors(text, LIGHT_START)
    dark = parse_colors(text, DARK_START)
    lines = [
        "// GENERATED by scripts/generate_android_theme.py from web/src/gc-tokens.css.",
        "// Source: GoreeCloud/gc-ui (MIT), see docs/THIRD_PARTY.md. DO NOT EDIT.",
        "package com.goreecloud.backup",
        "",
        "import androidx.compose.material3.darkColorScheme",
        "import androidx.compose.material3.lightColorScheme",
        "import androidx.compose.ui.graphics.Color",
        "",
        "internal object GoreeCloudUiTheme {",
    ]
    for theme, factory, values in (
        ("Light", "lightColorScheme", light),
        ("Dark", "darkColorScheme", dark),
    ):
        lines.append(f"    val {theme} = {factory}(")
        for role, token in ROLES:
            value = values[token].replace("#", "0xFF")
            lines.append(f"        {role} = Color({value}), // --gc-{token}")
        lines.append("    )")
        lines.append("")
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="refuse stale generated Kotlin")
    args = parser.parse_args()
    try:
        expected = generate(SOURCE.read_text(encoding="utf-8"))
        if args.check:
            if not DESTINATION.is_file() or DESTINATION.read_text(encoding="utf-8") != expected:
                raise ValueError("Android colors are out of sync with the canonical tracked GC UI CSS")
            print("PASS: Android Material3 colors match verified GC UI light/dark CSS tokens")
        else:
            DESTINATION.write_text(expected, encoding="utf-8")
            print(f"Generated {DESTINATION.relative_to(ROOT)}")
        return 0
    except (OSError, ValueError) as exc:
        print(f"GC UI theme generation failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
